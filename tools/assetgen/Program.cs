// assetgen: scans a game's assets folder and writes a C++ header of path constants.
//
// Usage: assetgen <assets-dir> <output-header> [--namespace Assets]
//
// assets/ui/buttons/red_button.png becomes
//   namespace Assets::UI::Buttons { inline constexpr std::string_view RED_BUTTON = "assets/ui/buttons/red_button.png"; }
// Paths are written relative to the assets folder's parent, using forward slashes.

using System.Reflection;
using System.Text;

return AssetGen.Run(args);

static class AssetGen
{
    // Folder words that read better as acronyms than PascalCase ("ui" -> "UI", not "Ui").
    static readonly HashSet<string> Acronyms = new(StringComparer.OrdinalIgnoreCase)
    {
        "ui", "hud", "gui", "fx", "sfx", "vfx", "bgm", "ost", "ai", "npc", "2d", "3d",
    };

    static readonly HashSet<string> CppKeywords = new(StringComparer.Ordinal)
    {
        "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break", "case",
        "catch", "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept", "const", "consteval",
        "constexpr", "constinit", "const_cast", "continue", "co_await", "co_return", "co_yield", "decltype",
        "default", "delete", "do", "double", "dynamic_cast", "else", "enum", "explicit", "export", "extern",
        "false", "float", "for", "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new",
        "noexcept", "not", "not_eq", "nullptr", "operator", "or", "or_eq", "private", "protected", "public",
        "register", "reinterpret_cast", "requires", "return", "short", "signed", "sizeof", "static",
        "static_assert", "static_cast", "struct", "switch", "template", "this", "thread_local", "throw", "true",
        "try", "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual", "void", "volatile",
        "wchar_t", "while", "xor", "xor_eq",
    };

    public static int Run(string[] args)
    {
        string rootNamespace = "Assets";
        var positional = new List<string>();

        for (int i = 0; i < args.Length; i++)
        {
            if (args[i] is "--namespace" or "-n" && i + 1 < args.Length)
                rootNamespace = args[++i];
            else if (args[i] is "--help" or "-h")
                return Usage(0);
            else if (args[i] is "--version")
            {
                Console.WriteLine(typeof(AssetGen).Assembly
                    .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion ?? "unknown");
                return 0;
            }
            else
                positional.Add(args[i]);
        }

        if (positional.Count != 2)
            return Usage(1);

        var assetsDir = new DirectoryInfo(Path.GetFullPath(positional[0]));
        string outputPath = Path.GetFullPath(positional[1]);

        if (!assetsDir.Exists)
        {
            Console.Error.WriteLine($"assetgen: assets folder not found: {assetsDir.FullName}");
            return 1;
        }

        try
        {
            string header = Generate(assetsDir, rootNamespace);
            bool written = WriteIfChanged(outputPath, header);
            Console.WriteLine(written
                ? $"assetgen: wrote {outputPath}"
                : $"assetgen: {outputPath} is up to date");
            return 0;
        }
        catch (AssetGenException e)
        {
            Console.Error.WriteLine($"assetgen: {e.Message}");
            return 1;
        }
    }

    static int Usage(int code)
    {
        var w = code == 0 ? Console.Out : Console.Error;
        w.WriteLine("Usage: assetgen <assets-dir> <output-header> [--namespace Assets]");
        w.WriteLine("       assetgen --version");
        return code;
    }

    static string Generate(DirectoryInfo assetsDir, string rootNamespace)
    {
        // Paths are relative to the parent so they start with the assets folder name, e.g. "assets/...".
        string baseDir = assetsDir.Parent?.FullName ?? assetsDir.FullName;

        var sb = new StringBuilder();
        sb.Append("// Generated by assetgen. Do not edit by hand; rerun the tool instead.\n");
        sb.Append("#pragma once\n\n");
        sb.Append("#include <string_view>\n");

        foreach (var (ns, constants) in CollectNamespaces(assetsDir, rootNamespace, baseDir))
        {
            int width = constants.Max(c => c.Name.Length);
            sb.Append('\n');
            sb.Append($"namespace {ns} {{\n");
            foreach (var (name, path) in constants)
                sb.Append($"    inline constexpr std::string_view {name.PadRight(width)} = \"{EscapeCpp(path)}\";\n");
            sb.Append("}\n");
        }

        return sb.ToString();
    }

    // Walks the tree and returns one entry per folder that directly contains files.
    static List<(string Namespace, List<(string Name, string Path)> Constants)> CollectNamespaces(
        DirectoryInfo root, string rootNamespace, string baseDir)
    {
        var result = new List<(string, List<(string, string)>)>();
        Walk(root, [rootNamespace]);
        return result;

        void Walk(DirectoryInfo dir, List<string> nsParts)
        {
            var files = dir.EnumerateFiles()
                .Where(f => !IsHidden(f))
                .OrderBy(f => f.Name, StringComparer.Ordinal)
                .ToList();
            var subdirs = dir.EnumerateDirectories()
                .Where(d => !IsHidden(d))
                .OrderBy(d => d.Name, StringComparer.Ordinal)
                .ToList();

            // Namespace and constant names share a scope in C++, so check for clashes between them.
            var subNamespaces = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var sub in subdirs)
            {
                string part = ToNamespacePart(sub.Name);
                if (subNamespaces.TryGetValue(part, out var other))
                    throw new AssetGenException(
                        $"folders '{other}' and '{sub.Name}' in {dir.FullName} both map to namespace '{part}'");
                subNamespaces[part] = sub.Name;
            }

            if (files.Count > 0)
            {
                var constants = BuildConstants(files, baseDir);
                foreach (var (name, path) in constants)
                {
                    if (subNamespaces.TryGetValue(name, out var folder))
                        throw new AssetGenException(
                            $"'{path}' and folder '{folder}' both map to the name '{name}' in {string.Join("::", nsParts)}");
                }
                result.Add((string.Join("::", nsParts), constants));
            }

            foreach (var sub in subdirs)
                Walk(sub, [.. nsParts, ToNamespacePart(sub.Name)]);
        }
    }

    static List<(string Name, string Path)> BuildConstants(List<FileInfo> files, string baseDir)
    {
        // Name by file stem; when two files share a stem (jump.wav, jump.ogg), add the extension to each.
        var byName = files
            .Select(f => (File: f, Name: ToConstantName(Path.GetFileNameWithoutExtension(f.Name))))
            .GroupBy(x => x.Name, StringComparer.Ordinal)
            .SelectMany(g => g.Count() == 1
                ? g
                : g.Select(x => (x.File, Name: $"{x.Name}_{ToConstantName(x.File.Extension.TrimStart('.'))}")))
            .ToList();

        var dupes = byName.GroupBy(x => x.Name).FirstOrDefault(g => g.Count() > 1);
        if (dupes is not null)
            throw new AssetGenException(
                $"files {string.Join(", ", dupes.Select(x => x.File.Name))} in {files[0].DirectoryName} " +
                $"all map to the name '{dupes.Key}'");

        return byName
            .Select(x => (x.Name, Path.GetRelativePath(baseDir, x.File.FullName).Replace('\\', '/')))
            .ToList();
    }

    // "buttons" -> "Buttons", "ui" -> "UI", "main_menu" -> "MainMenu"
    static string ToNamespacePart(string folderName)
    {
        var words = SplitWords(folderName);
        string name = string.Concat(words.Select(w =>
            Acronyms.Contains(w) ? w.ToUpperInvariant() : char.ToUpperInvariant(w[0]) + w[1..].ToLowerInvariant()));
        return MakeIdentifier(name);
    }

    // "red_button" -> "RED_BUTTON", "redButton" -> "RED_BUTTON", "tile-01" -> "TILE_01"
    static string ToConstantName(string stem)
    {
        string name = string.Join("_", SplitWords(stem).Select(w => w.ToUpperInvariant()));
        return MakeIdentifier(name);
    }

    // Splits on any non-alphanumeric character and on lower->upper camelCase boundaries.
    static List<string> SplitWords(string s)
    {
        var words = new List<string>();
        var current = new StringBuilder();
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            if (!char.IsAsciiLetterOrDigit(c))
            {
                Flush();
                continue;
            }
            if (char.IsUpper(c) && current.Length > 0 && char.IsLower(current[^1]))
                Flush();
            current.Append(c);
        }
        Flush();
        return words;

        void Flush()
        {
            if (current.Length > 0) words.Add(current.ToString());
            current.Clear();
        }
    }

    static string MakeIdentifier(string name)
    {
        if (name.Length == 0) name = "_";
        if (char.IsAsciiDigit(name[0])) name = "_" + name;
        if (CppKeywords.Contains(name)) name += "_";
        return name;
    }

    static bool IsHidden(FileSystemInfo info) =>
        info.Name.StartsWith('.') || info.Attributes.HasFlag(FileAttributes.Hidden);

    static string EscapeCpp(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    // Skips the write when nothing changed so the C++ build doesn't recompile everything.
    static bool WriteIfChanged(string path, string contents)
    {
        if (File.Exists(path) && File.ReadAllText(path) == contents)
            return false;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, contents, new UTF8Encoding(false));
        return true;
    }
}

sealed class AssetGenException(string message) : Exception(message);
